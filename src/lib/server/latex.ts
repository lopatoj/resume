import { plainResumeText } from '#lib/resume-text.ts';
import { execFile } from 'node:child_process';
import { copyFile, mkdir, mkdtemp, readFile, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { promisify } from 'node:util';
import { bulletText } from './store.ts';
import type { Application, Experience, Layout, LayoutIssue, Profile, SelectedBullet } from '#lib/types.ts';

const run = promisify(execFile);
const LATEX = path.resolve('latex');
const CACHE = path.resolve('.cache');

/** A bullet whose last line is filled less than this is flagged as a widow. */
export const WIDOW_FILL = 0.3;

/** Visible text of a bullet on this job's resume, with any what-if overrides applied. */
const selectedText = (register: Experience[], b: SelectedBullet, overrides: Record<string, string>) =>
	overrides[b.bullet] ?? bulletText(register, b);

/** Every bullet original and variant in the register, keyed as in Layout.alternatives. */
function alternativeTexts(register: Experience[]): [string, string][] {
	return register.flatMap((e) =>
		e.bullets.flatMap((b) => [[`b:${b.id}`, b.text] as [string, string], ...(b.variants ?? []).map((v) => [`v:${v.id}`, v.text] as [string, string])])
	);
}

/**
 * With `measure` off, the output is plain LaTeX that compiles with just resume.cls.
 * `overrides` replaces the text of selected bullets (by bullet id) for what-if measurement.
 */
export function renderTex(
	profile: Profile,
	register: Experience[],
	job: Application,
	measure = true,
	overrides: Record<string, string> = {}
): string {
	const byId = new Map(register.map((e) => [e.id, e]));
	const selected = job.selection
		.map((s) => {
			const exp = byId.get(s.experience);
			// Skip anything deleted from the register since the job was saved.
			return { exp, bullets: s.bullets.filter((b) => exp?.bullets.some((eb) => eb.id === b.bullet)) };
		})
		.filter((s): s is { exp: Experience; bullets: typeof s.bullets } => !!s.exp && s.bullets.length > 0);

	const section = (heading: string, kind: Experience['kind']) => {
		const items = selected.filter((s) => s.exp.kind === kind);
		if (items.length === 0) return '';
		const body = items.map(({ exp, bullets }) => {
			const header =
				exp.kind === 'experience'
					? `    \\experienceItem[
        company={${exp.company}},
        location={${exp.location}},
        position={${exp.position}},
        duration={${exp.duration}}
    ]`
					: `    \\projectItem[
        title={${exp.title}},
        duration={${exp.duration}}
    ]`;
			const items = bullets
				.map((b) =>
					measure
						? `        \\rbullet{${b.bullet}}{${selectedText(register, b, overrides)}}`
						: `        \\item ${selectedText(register, b, overrides)}`
				)
				.join('\n');
			const vspace = exp.kind === 'experience' ? '-0.2em' : '-0.5em';
			return `${header}
    \\begin{itemize}
        \\vspace{${vspace}}
        \\itemsep -6pt {}
${items}
    \\end{itemize}`;
		});
		return `\\begin{experienceSection}{${heading}}
${body.join('\n')}
\\end{experienceSection}
`;
	};

	const skills = (job.skills ?? profile.skills)
		.filter((g) => g.items.length > 0)
		.map((g) => `\\textbf{${g.category}:} ${g.items.join(', ')}`)
		.join(' \\\\\n');
	const ed = profile.education;

	return `% Generated by resume-tailor — edit data/*.yaml instead.
\\documentclass{resume}
${measure ? '\\usepackage{tailor}\n' : ''}
\\setlength{\\tabcolsep}{0pt}
\\usepackage{enumitem}
\\setlist[itemize]{leftmargin=1em, labelsep=0.4em}

\\begin{document}

\\introduction[
    fullname={${profile.name}},
    email={${profile.email}},
    phone={${profile.phone}},
    linkedin={${profile.linkedin}},
    github={${profile.github}},
    website={${profile.website}}
]

\\begin{educationSection}{Education}
    \\educationItem[
        university={${ed.university}},
        college={${ed.college}},
        graduation={${ed.graduation}},
        gpa={${ed.gpa}},
        program={${ed.program}},
    ]
${ed.coursework ? `    \\textbf{Coursework:} ${ed.coursework}\n` : ''}\\end{educationSection}
\\vspace{-1.5em}

${section('Experience', 'experience')}
${section('Projects \\& Leadership', 'project')}
\\sectionTitle{Technical Skills}
${skills}

\\sectionTitle{Awards}
${profile.awards}
${
	measure
		? `
\\begin{tailoralternatives}
${alternativeTexts(register)
	.map(([key, text]) => `\\rmeasure{${key}}{${text}}`)
	.join('\n')}
\\end{tailoralternatives}
`
		: ''
}
\\end{document}
`;
}

const toPt = (s: string) => parseFloat(s);

/** Approximate visible length of LaTeX bullet text. */
const plainLength = (tex: string) => plainResumeText(tex).length;

export interface BuildResult {
	pdf?: Buffer;
	layout: Layout;
}

/** Compiles and measures. `texts` maps each measured id or key to its LaTeX text. */
export async function compile(tex: string, texts: Record<string, string>): Promise<BuildResult> {
	const dir = await mkdtemp(path.join(tmpdir(), 'resume-'));
	try {
		await writeFile(path.join(dir, 'resume.tex'), tex);
		await copyFile(path.join(LATEX, 'resume.cls'), path.join(dir, 'resume.cls'));
		await copyFile(path.join(LATEX, 'tailor.sty'), path.join(dir, 'tailor.sty'));

		const layout: Layout = {
			pages: 0,
			freeSpace: 0,
			lineHeight: 12,
			itemGap: 0,
			pageLines: 0,
			freeLines: 0,
			overflowLines: 0,
			bullets: {},
			alternatives: {},
			issues: []
		};
		try {
			await run('pdflatex', ['-interaction=nonstopmode', '-halt-on-error', 'resume.tex'], {
				cwd: dir,
				timeout: 30_000
			});
		} catch {
			const log = await readFile(path.join(dir, 'resume.log'), 'utf8').catch(() => '');
			const message =
				log
					.split('\n')
					.filter((l) => l.startsWith('!'))
					.join('\n') || 'pdflatex failed (is it installed?)';
			layout.issues.push({ kind: 'latex', message });
			return { layout };
		}

		const meas = await readFile(path.join(dir, 'resume.meas'), 'utf8');
		let used = 0;
		let goal = 0;
		for (const line of meas.split('\n')) {
			const [kind, ...f] = line.trim().split(/\s+/);
			if (kind === 'BULLET' || kind === 'ALT') {
				const [id, lines, last, width] = f;
				// A line that TeX shrank to fit has natural width above \linewidth; it still fits.
				const fill = Math.min(1, toPt(last) / toPt(width));
				const n = Number(lines);
				const measured = { lines: n, fill, charsPerLine: Math.round(plainLength(texts[id] ?? '') / (n - 1 + fill)) };
				(kind === 'BULLET' ? layout.bullets : layout.alternatives)[id] = measured;
			} else if (kind === 'METRICS') {
				layout.lineHeight = toPt(f[0]);
				layout.itemGap = toPt(f[1]) + toPt(f[2]);
			} else if (kind === 'PAGE') {
				layout.pages = Number(f[0]);
				used = toPt(f[1]);
				goal = toPt(f[2]);
			}
		}
		layout.freeSpace = layout.pages === 1 ? Math.max(0, goal - used) : 0;
		layout.pageLines = goal / layout.lineHeight;
		layout.freeLines = layout.freeSpace / layout.lineHeight;
		// Past one page: everything on the pages after the first.
		layout.overflowLines = layout.pages > 1 ? ((layout.pages - 2) * goal + used) / layout.lineHeight : 0;

		const issues: LayoutIssue[] = [];
		if (layout.pages > 1) issues.push({ kind: 'overflow', pages: layout.pages });
		for (const [bullet, b] of Object.entries(layout.bullets)) {
			if (b.lines > 1 && b.fill < WIDOW_FILL) issues.push({ kind: 'widow', bullet, fill: b.fill });
		}
		layout.issues = issues;

		return { pdf: await readFile(path.join(dir, 'resume.pdf')), layout };
	} finally {
		await rm(dir, { recursive: true, force: true });
	}
}

/** Renders, compiles and measures a job's resume; `overrides` replaces selected bullets' text (what-if). */
export async function build(
	profile: Profile,
	register: Experience[],
	job: Application,
	overrides: Record<string, string> = {}
) {
	const tex = renderTex(profile, register, job, true, overrides);
	const texts = Object.fromEntries([
		...job.selection.flatMap((s) => s.bullets.map((b) => [b.bullet, selectedText(register, b, overrides)])),
		...alternativeTexts(register)
	]);
	return { tex, ...(await compile(tex, texts)) };
}

export async function cachePdf(slug: string, pdf: Buffer) {
	await mkdir(CACHE, { recursive: true });
	await writeFile(path.join(CACHE, `${slug}.pdf`), pdf);
}

export const cachedPdf = (slug: string) => readFile(path.join(CACHE, `${slug}.pdf`));

export const dropCachedPdf = (slug: string) => rm(path.join(CACHE, `${slug}.pdf`), { force: true });
